function [d, report] = build_census_datasets_rev1(cfg)
%BUILD_CENSUS_DATASETS_REV1 Build, validate, and save every dataset.
%   [d, report] = build_census_datasets_rev1(cfg)
%
%   Outputs, saved in cfg.data_folder (data/tiger<year>/) with the legacy
%   file and variable names:
%     Cascade_new_full_census_2020.mat          new_full_census_2020      (F1)
%     Cascade_new_full_census_2023_UA.mat       new_full_census_2020      (F2)
%     cell_urbanarea_census_data_2020_2023.mat  cell_ua_census_data_2020
%     cell_pea_census_data_2020_2023.mat        cell_pea_census_data_2020
%   plus census_2020_tracts.csv (F2 as text), cfg.file.manifest,
%   validation_report.md in cfg.report_folder, and, in the cache folder, the
%   urban area cell with boundaries (..._contours_tiger<year>.mat).
%   The file names keep "2023" so that existing code loads them unchanged.

arguments
    cfg (1,1) struct
end

dl = @(url, sub) download_source_rev1(url, fullfile(cfg.cache_folder, sub), cfg.tf_redownload, cfg.download_retries);
unzip_folder = fullfile(cfg.cache_folder, "unzip");

%%%%%%%%%% State list: every state-equivalent with a TIGER/Line state record
state_zip = dl(cfg.url.state, "other");
st = readgeotable(read_shapefile_zip_rev1(state_zip, unzip_folder));
state_fips = sort(string(st.STATEFP));
fprintf("%d state-equivalents\n", numel(state_fips));

%%%%%%%%%% Tracts
tract_zips = strings(numel(state_fips), 1);
for k = 1:numel(state_fips)
    tract_zips(k) = dl(sprintf(cfg.url.tract, state_fips(k)), "tract");
end
tract_tbl = read_tract_points_rev1(tract_zips, unzip_folder);
fprintf("%d tracts\n", height(tract_tbl));

%%%%%%%%%% Blocks -> tract sums and urban pieces (or the committed CSV files)
[tract_sum, ua_pieces] = build_block_summaries_rev1(cfg, tract_tbl, state_fips);

%%%%%%%%%% Tract arrays
[pea_names, pea_counties, county_changes] = read_pea_tables_rev1(cfg);
[d.F1, d.F2] = build_tract_arrays_rev1(tract_tbl, tract_sum, pea_counties, county_changes);

%%%%%%%%%% Urban area and PEA cells
uac_shp = read_shapefile_zip_rev1(dl(cfg.url.uac, "other"), unzip_folder);
[d.ua, ua_contours] = build_ua_cell_rev2(d.F2, ua_pieces, uac_shp);
d.pea = build_pea_cell_rev1(d.F2, pea_names, cfg.file.pea_shp);

%%%%%%%%%% Validate (errors before anything is saved)
checks = read_check_sources_rev1(cfg);
report = validate_census_datasets_rev1(d, cfg.expected, checks);

%%%%%%%%%% Save
new_full_census_2020 = d.F1;
save(fullfile(cfg.data_folder, "Cascade_new_full_census_2020.mat"), "new_full_census_2020", "-v7");
new_full_census_2020 = d.F2;
save(fullfile(cfg.data_folder, "Cascade_new_full_census_2023_UA.mat"), "new_full_census_2020", "-v7");
cell_ua_census_data_2020 = d.ua;
save(fullfile(cfg.data_folder, "cell_urbanarea_census_data_2020_2023.mat"), "cell_ua_census_data_2020", "-v7");
cell_ua_census_data_2020 = ua_contours;
save(fullfile(cfg.cache_folder, "cell_urbanarea_census_data_2020_2023_contours_tiger" + cfg.tiger_year + ".mat"), "cell_ua_census_data_2020", "-v7.3");
cell_pea_census_data_2020 = d.pea;
save(fullfile(cfg.data_folder, "cell_pea_census_data_2020_2023.mat"), "cell_pea_census_data_2020", "-v7");

tract_csv = array2table(new_full_census_2020, 'VariableNames', ...
    {'GEOID', 'LAT', 'LON', 'POP', 'UACE', 'PEA_NUM', 'URBAN_POP'});
tract_csv.GEOID = compose("%011d", tract_csv.GEOID);
writetable(tract_csv, fullfile(cfg.data_folder, "census_2020_tracts.csv"));

if cfg.tf_write_manifest
    write_manifest_rev1(cfg);
end
write_report_rev1(cfg, report);
end

function write_report_rev1(cfg, report)
report_folder = cfg.report_folder;
if ~isfolder(report_folder)
    mkdir(report_folder);
end
lines = ["# Validation report", "", ...
    "Generated by `build_census_datasets_rev1` on " + string(datetime("now", "Format", "yyyy-MM-dd")) + ...
    " from TIGER/Line " + cfg.tiger_year + ".", "", ...
    "| Check | Result | Detail |", "|---|---|---|"];
res = repmat("Pass", height(report), 1);
res(~report.Pass) = "FAIL";
lines = [lines, ("| " + report.Check + " | " + res + " | " + report.Detail + " |")'];
writelines(lines, fullfile(report_folder, "validation_report.md"));
end
