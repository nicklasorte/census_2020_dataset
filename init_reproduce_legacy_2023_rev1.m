%INIT_REPRODUCE_LEGACY_2023_REV1 Rebuild from TIGER/Line 2023 and compare with the legacy files.
%   The legacy Census_Functions files were built from TIGER/Line 2023. This
%   script runs the same build with tiger_year = 2023 into cache/build_2023
%   (data/ is not touched), then compares every legacy column element by
%   element, and writes reports/legacy_2023_reproduction.md.
%
%   First run downloads the 2023 tract and block files (about 6 GB).

clear; close all;
repo_folder = string(fileparts(mfilename("fullpath")));
addpath(fullfile(repo_folder, "src"));

cfg = census_config_rev1(repo_folder, fullfile(repo_folder, "cache"), 2023);
out_folder = fullfile(cfg.cache_folder, "build_2023");
cfg.derived_folder = fullfile(out_folder, "derived");
cfg.data_folder = out_folder;
cfg.report_folder = out_folder;
cfg.tf_rebuild_blocks = true;    % 2023 block results aren't committed
cfg.tf_write_manifest = false;
if ~isfolder(out_folder)
    mkdir(out_folder);
end

d = build_census_datasets_rev1(cfg);

%%%%%%%%%% Legacy files
legacy_folder = fullfile(cfg.cache_folder, "legacy");
lg = @(u) download_source_rev1(u, legacy_folder, false, cfg.download_retries);
L20 = load(lg(cfg.url.legacy_2020), "new_full_census_2020").new_full_census_2020;
LUA = load(lg(cfg.url.legacy_ua), "new_full_census_2020").new_full_census_2020;
LPEA = load(lg(cfg.url.legacy_pea), "cell_pea_census_data_2020").cell_pea_census_data_2020;
LUC = load(lg(replace(cfg.url.legacy_ua, "Cascade_new_full_census_2023_UA.mat", "cell_urbanarea_census_data_2020_2023.mat")), ...
    "cell_ua_census_data_2020").cell_ua_census_data_2020;

%%%%%%%%%% Compare
rows = strings(0, 2);
yn_list = ["Different", "Identical"];
yn = @(tf) yn_list(double(all(tf)) + 1);

F2 = d.F2;
rows(end + 1, :) = ["Tract array: same tracts in the same row order", yn(isequal(F2(:, 1), LUA(:, 1)))];
rows(end + 1, :) = ["Tract array: latitude and longitude (columns 2-3)", yn(isequal(F2(:, 2:3), LUA(:, 2:3)))];
rows(end + 1, :) = ["Tract array: population (column 4) vs legacy UA file", yn(isequal(F2(:, 4), LUA(:, 4)))];
same_ua = F2(:, 5) == LUA(:, 5) | (isnan(F2(:, 5)) & isnan(LUA(:, 5)));
rows(end + 1, :) = ["Tract array: urban area (column 5)", yn(all(same_ua)) + sprintf(" (%d tracts differ: %s)", nnz(~same_ua), ...
    strjoin(compose("%011d", F2(~same_ua, 1)), ", "))];
n20 = nnz(d.F1(:, 4) ~= L20(:, 4));
rows(end + 1, :) = ["2020 file: population vs legacy Cascade_new_full_census_2020", yn(n20 == 0) + sprintf(" (%d tracts differ)", n20)];
rows(end + 1, :) = ["2020 file: GEOID and location vs legacy Cascade_new_full_census_2020", yn(isequal(d.F1(:, 1:3), L20(:, 1:3)))];

% Urban area cell, legacy columns 1-9
ua = d.ua;
rows(end + 1, :) = ["UA cell: same urban areas in the same order", yn(isequal(cell2mat(ua(:, 2)), cell2mat(LUC(:, 2))))];
if size(ua, 1) == size(LUC, 1)
    for col = [1 4 5 6 7 9]
        diff_rows = find(~cellfun(@isequal, ua(:, col), LUC(:, col)));
        msg = yn(isempty(diff_rows)) + sprintf(" (%d rows differ)", numel(diff_rows));
        if ~isempty(diff_rows)
            msg = msg + ": " + strjoin(string(ua(diff_rows, 1)), "; ");
        end
        rows(end + 1, :) = [sprintf("UA cell: column %d", col), msg];
    end
end

% PEA cell, legacy columns 1-9
pea = d.pea;
for col = [1 2 3 5]
    diff_rows = find(~cellfun(@isequaln, pea(:, col), LPEA(:, col)));
    rows(end + 1, :) = [sprintf("PEA cell: column %d", col), yn(isempty(diff_rows)) + sprintf(" (%d rows differ)", numel(diff_rows))];
end
legacy_g = vertcat(LPEA{:, 6});
diff_rows = find(cellfun(@(a, b) ~isequal(a(ismember(a, legacy_g)), b), pea(:, 6), LPEA(:, 6)));
rows(end + 1, :) = ["PEA cell: column 6, tracts the legacy file assigned", yn(isempty(diff_rows)) + sprintf(" (%d rows differ)", numel(diff_rows))];
extra = setdiff(F2(:, 1), legacy_g);
rows(end + 1, :) = ["PEA cell: tracts the legacy file left out", sprintf("%d tracts, %d people", numel(extra), sum(F2(ismember(F2(:, 1), extra), 4)))];

report = table(rows(:, 1), rows(:, 2), 'VariableNames', {'Comparison', 'Result'});
disp(report);
lines = ["# Rebuild from TIGER/Line 2023 compared with the legacy files", "", ...
    "Generated by `init_reproduce_legacy_2023_rev1` on " + string(datetime("now", "Format", "yyyy-MM-dd")) + ...
    ". Same code as the main build, with `tiger_year = 2023`.", "", "| Comparison | Result |", "|---|---|", ...
    ("| " + report.Comparison + " | " + report.Result + " |")'];
writelines(lines, fullfile(repo_folder, "reports", "legacy_2023_reproduction.md"));
