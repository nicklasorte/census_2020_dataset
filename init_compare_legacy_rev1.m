%INIT_COMPARE_LEGACY_REV1 Compare the rebuilt datasets with the legacy Census_Functions files.
%   Writes reports/legacy_comparison_tracts.csv (one row per tract) and
%   reports/legacy_comparison.md (summary and largest differences).
%   Downloads the three legacy files from GitHub into cache/legacy.

clear; close all;
repo_folder = string(fileparts(mfilename("fullpath")));
addpath(fullfile(repo_folder, "src"));
cfg = census_config_rev1(repo_folder);

d.F2 = load(fullfile(cfg.data_folder, "Cascade_new_full_census_2023_UA.mat"), "new_full_census_2020").new_full_census_2020;
[cmp, summary] = compare_legacy_datasets_rev1(cfg, d);
disp(summary);

%%%%%%%%%% Markdown summary
fmt = @(v) string(compose("%.15g", v));
lines = ["# Comparison with the legacy Census_Functions files", "", ...
    "Generated by `init_compare_legacy_rev1` on " + string(datetime("now", "Format", "yyyy-MM-dd")) + ...
    ". Per-tract values: [legacy_comparison_tracts.csv](legacy_comparison_tracts.csv).", "", ...
    "Legacy files: TIGER/Line 2023. New files: TIGER/Line " + cfg.tiger_year + ". Population deltas are new minus legacy.", "", ...
    "| Measure | Value |", "|---|---|", ("| " + summary.Measure + " | " + fmt(summary.Value) + " |")', "", ...
    "## Largest population differences, legacy Cascade_new_full_census_2020", "", ...
    "| GEOID | New | Legacy | Delta |", "|---|---|---|---|"];
[~, order_idx] = sort(abs(cmp.DELTA_POP_2020), "descend");
top = cmp(order_idx(1:15), :);
lines = [lines, ("| " + top.GEOID + " | " + fmt(top.POP_NEW) + " | " + fmt(top.POP_LEGACY_2020) + " | " + fmt(top.DELTA_POP_2020) + " |")', "", ...
    "## Largest location shifts", "", "| GEOID | Shift (m) |", "|---|---|"];
[~, order_idx] = sort(cmp.LOCATION_SHIFT_M, "descend");
top = cmp(order_idx(1:10), :);
lines = [lines, ("| " + top.GEOID + " | " + compose("%.0f", top.LOCATION_SHIFT_M) + " |")'];
writelines(lines, fullfile(cfg.report_folder, "legacy_comparison.md"));
